    for name, data in pairs(_G.RAY_SavedPositions) do
        if data.Time and data.Time > lastTime then
            lastTime = data.Time
            lastSaved = name
        end
    end
    
    if lastSaved then
        TeleportToSaved(lastSaved)
    end
end)

